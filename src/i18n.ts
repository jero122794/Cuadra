export const lang = (typeof navigator !== "undefined" && (navigator.language || "es").toLowerCase().startsWith("es")) ? "es" : "en";
const table: Record<Key, string> = lang === "es" ? es : en;

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s = table[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}
